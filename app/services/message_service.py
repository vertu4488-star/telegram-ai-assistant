"""Message service orchestrating conversation persistence."""

from typing import List, Sequence

from app.config import settings
from app.database.database import get_db_session
from app.database.models import Message
from app.database.repository import MessageRepository


class MessageService:
    """Service handling conversation history storage and retrieval."""

    @staticmethod
    async def save_user_message(telegram_id: int, content: str) -> Message:
        """Store a message sent by the user."""
        async with get_db_session() as session:
            return await MessageRepository.save_message(
                session=session,
                telegram_id=telegram_id,
                role="user",
                content=content,
            )

    @staticmethod
    async def save_assistant_message(telegram_id: int, content: str) -> Message:
        """Store a response generated by the AI assistant."""
        async with get_db_session() as session:
            return await MessageRepository.save_message(
                session=session,
                telegram_id=telegram_id,
                role="assistant",
                content=content,
            )

    @staticmethod
    async def get_conversation_history(
        telegram_id: int, limit: int | None = None
    ) -> Sequence[Message]:
        """Fetch chronological conversation history up to the configured limit."""
        actual_limit = limit or settings.MAX_HISTORY_MESSAGES
        async with get_db_session() as session:
            return await MessageRepository.get_recent_messages(
                session=session,
                telegram_id=telegram_id,
                limit=actual_limit,
            )

    @staticmethod
    async def clear_conversation(telegram_id: int) -> int:
        """Clear all conversation history for the user."""
        async with get_db_session() as session:
            return await MessageRepository.clear_history(
                session=session,
                telegram_id=telegram_id,
            )
